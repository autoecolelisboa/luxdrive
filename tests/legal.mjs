// Pages légales : accessibles sans connexion et connecté ; e-mail du créateur jamais écrit en clair.
import { chromium } from '@playwright/test';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 400, height: 860 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  ✓', m); } else { fail++; console.log('  ✗', m); } };
const vis = (loc) => loc.waitFor({ timeout: 15000 }).then(() => true, () => false);
await page.goto('http://localhost:4173/?memoire');
await page.getByText('Mode démonstration').waitFor({ timeout: 60000 });
ok(await vis(page.getByText('© 2026 Auto École Lisboa')), 'Pied de page sur la connexion');
ok(await vis(page.getByRole('button', { name: 'HMA Productions' })), 'Crédit HMA Productions cliquable');
ok(!(await page.content()).includes('hma.lux07@gmail.com'), "L'e-mail n'apparaît pas dans la page");
await page.getByRole('link', { name: 'Mentions légales' }).click();
ok(await vis(page.getByRole('heading', { name: 'Mentions légales' })), 'Mentions légales sans connexion');
ok(await vis(page.getByText('Tous droits réservés', { exact: false }).first()), 'Droits HMA Productions');
ok(await vis(page.getByText('à compléter').first()), 'Champs manquants signalés (« à compléter »)');
await page.goto('http://localhost:4173/?memoire#/legal/conditions');
ok(await vis(page.getByText('Annulation gratuite jusqu’à 48 heures')), 'Conditions : règle des 48 h');
ok(await vis(page.getByText('Forfait 2 leçons')), 'Conditions : tarifs à jour');
ok(await vis(page.getByText('295,00')), 'Conditions : inscription 295 €');
await page.goto('http://localhost:4173/?memoire#/legal/confidentialite');
ok(await vis(page.getByText('CNPD', { exact: false })), 'Confidentialité : CNPD');
await page.getByRole('button', { name: 'PT', exact: true }).count().then(async n => { if (n) await page.getByRole('button', { name: 'PT', exact: true }).click(); });
await page.goto('http://localhost:4173/?memoire#/');
await page.getByRole('button', { name: /Carla Lisboa/ }).click();
await page.locator('.bottomnav').waitFor({ timeout: 20000 });
await page.locator('.bottomnav').getByRole('link', { name: 'Réglages', exact: true }).click();
ok(await vis(page.getByText('À compléter : ces informations sont obligatoires')), 'Réglages : rappel à compléter');
await page.getByLabel('N° RCS').fill('B123456');
await page.getByLabel('Forme juridique').fill('s.à r.l.');
await page.getByRole('button', { name: 'Enregistrer' }).first().click();
await page.locator('.toast', { hasText: 'Enregistré' }).waitFor({ timeout: 15000 }).catch(() => {});
await page.getByRole('link', { name: 'Mentions légales' }).click();
ok(await vis(page.getByText('B123456')), 'RCS affiché dans les mentions légales');
ok(await vis(page.getByText('s.à r.l.')), 'Forme juridique affichée');
console.log('Erreurs JS :', errors.length ? errors : 'aucune'); ok(errors.length === 0, 'Aucune erreur');
console.log(`\n${pass} réussis, ${fail} échoués`);
await browser.close(); process.exit(fail ? 1 : 0);
