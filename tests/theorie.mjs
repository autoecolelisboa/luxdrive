// Bureau : séance de théorie, inscription, examens ; élève : voit sa séance et son examen.
import { chromium } from '@playwright/test';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  ✓', m); } else { fail++; console.log('  ✗', m); } };
const vis = (loc) => loc.waitFor({ timeout: 15000 }).then(() => true, () => false);
const toast = (txt) => page.locator('.toast', { hasText: txt }).waitFor({ timeout: 15000 }).then(() => true, () => false);
const nav = (n) => page.locator('.bottomnav').getByRole('link', { name: n, exact: true }).click();
const login = async (label) => {
  if (await page.locator('.demo-bar').count()) await page.getByRole('button', { name: 'Changer de compte' }).click();
  await page.getByRole('button', { name: new RegExp(label) }).click();
  await page.locator('.bottomnav').waitFor({ timeout: 20000 });
};
await page.goto('http://localhost:4173/?memoire');
await page.getByText('Mode démonstration').waitFor({ timeout: 60000 });
await login('Sara Mendes');
await nav('Théorie');
await page.getByRole('button', { name: 'Nouvelle séance' }).click();
await page.locator('.sheet input').first().fill('Règles de priorité');
await page.locator('.sheet').getByRole('button', { name: 'Créer' }).click();
ok(await toast('Enregistré'), 'Séance de théorie créée');
await page.getByRole('button', { name: /Règles de priorité/ }).click();
const v = await page.getByTestId('ajouter-eleve').locator('option', { hasText: 'Ana' }).getAttribute('value');
await page.getByTestId('ajouter-eleve').selectOption(v);
await page.locator('.sheet').getByRole('button', { name: 'Ajouter' }).click();
ok(await vis(page.locator('.sheet').getByText('1 inscrit(s)')), 'Ana inscrite à la séance');
await page.keyboard.press('Escape');
await nav('Élèves');
await page.getByRole('link', { name: /Inês Rodrigues/ }).click();
await page.getByRole('button', { name: '+ Examen' }).click();
await page.locator('.sheet').getByRole('button', { name: 'Créer' }).click();
ok(await toast('Enregistré'), 'Examen théorique ajouté');
await page.getByRole('button', { name: 'Réussi' }).click();
ok(await vis(page.locator('.badge', { hasText: 'Réussi' })), 'Résultat : réussi');
const d = await page.locator('input[type=date]').first().inputValue();
ok(d.length === 10, `Date de théorie réussie remplie automatiquement (${d})`);
await login('Ana Silva');
ok(await vis(page.getByText('Mes prochaines séances de théorie')), "L'élève voit sa prochaine séance");
ok(await vis(page.getByText('Règles de priorité')), 'Thème affiché');
await login('Marc Weber');
await nav('Théorie');
ok(await vis(page.getByText('Priorités et signalisation')), 'Le moniteur voit ses séances');
ok(await page.getByRole('button', { name: 'Nouvelle séance' }).count() === 0, 'Le moniteur ne crée pas de séance');
console.log('Erreurs JS :', errors.length ? errors : 'aucune'); ok(errors.length === 0, 'Aucune erreur');
console.log(`\n${pass} réussis, ${fail} échoués`);
await browser.close(); process.exit(fail ? 1 : 0);
